#!/usr/bin/env bash
# Removes Snapshotter for the current user. Downloaded videos are never touched.
set -euo pipefail

APP_ID="snapshotter"
DATA_HOME="${XDG_DATA_HOME:-$HOME/.local/share}"
APP_DIR="$DATA_HOME/$APP_ID"
LAUNCHER="$HOME/.local/bin/$APP_ID"
DESKTOP_DIR="$DATA_HOME/applications"
DESKTOP_FILE="$DESKTOP_DIR/$APP_ID.desktop"
ICON_ROOT="$DATA_HOME/icons/hicolor"

if [ "$(id -u)" -eq 0 ]; then
    echo "Error: run uninstall.sh as your normal user, not root." >&2
    exit 1
fi

remove() {
    if [ -e "$1" ] || [ -L "$1" ]; then
        rm -rf -- "$1"
        echo "  removed $1"
    fi
}

echo "Uninstalling Snapshotter…"

# Only delete the launcher if it is the one install.sh generated.
if [ -f "$LAUNCHER" ]; then
    if grep -q "Snapshotter launcher (generated by install.sh)" "$LAUNCHER" 2>/dev/null; then
        remove "$LAUNCHER"
    else
        echo "  kept $LAUNCHER (not created by Snapshotter's installer)"
    fi
fi

remove "$DESKTOP_FILE"
for icon in "$ICON_ROOT"/*/apps/"$APP_ID".png "$ICON_ROOT"/*/apps/"$APP_ID".svg; do
    [ -e "$icon" ] && remove "$icon"
done

# Sanity check before deleting the application directory (files + venv).
case "$APP_DIR" in
    */"$APP_ID") remove "$APP_DIR" ;;
    *) echo "  refusing to delete unexpected path $APP_DIR" >&2 ;;
esac

if command -v update-desktop-database >/dev/null 2>&1; then
    update-desktop-database -q "$DESKTOP_DIR" 2>/dev/null || true
fi
if command -v gtk-update-icon-cache >/dev/null 2>&1 && [ -f "$ICON_ROOT/index.theme" ]; then
    gtk-update-icon-cache -q -t -f "$ICON_ROOT" 2>/dev/null || true
fi
touch "$ICON_ROOT" 2>/dev/null || true
if command -v xdg-desktop-menu >/dev/null 2>&1; then
    xdg-desktop-menu forceupdate 2>/dev/null || true
fi

echo "Snapshotter has been removed. Your downloaded videos were not touched."
